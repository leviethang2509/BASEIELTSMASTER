import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const contractPath = path.join(rootDir, 'IELTSMaster.Shared', 'Security', 'permissions-contract.json');
if (!fs.existsSync(contractPath)) {
  console.error(`Contract file not found at: ${contractPath}`);
  process.exit(1);
}

const contract = JSON.parse(fs.readFileSync(contractPath, 'utf8'));

console.log(`[CodeGen] Loaded permissions contract v${contract.version} (${contract.lastUpdated})`);
console.log(`[CodeGen] System roles: ${contract.systemRoles.length}, Tenant roles: ${contract.tenantRoles.length}, Permissions: ${contract.permissions.length}`);

function toPascalCase(str) {
  return str
    .split(/[:\-_]/)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join('');
}

function toScreamingSnakeCase(str) {
  return str.replace(/[:\-]/g, '_').toUpperCase();
}

// 1. Generate C# Code
const csCode = `// <auto-generated>
// This code was generated by scripts/generate-permissions.mjs
// Source of Truth: IELTSMaster.Shared/Security/permissions-contract.json
// Version: ${contract.version} | Last Updated: ${contract.lastUpdated}
// </auto-generated>

using System;
using System.Collections.Generic;

namespace AUN_QA.Shared.Security
{
    public static class GeneratedPermissionKey
    {
${contract.permissions
  .map(
    (p) => `        /// <summary>${p.description} (${p.scope})</summary>
        public const string ${toPascalCase(p.key)} = "${p.key}";`
  )
  .join('\n\n')}

        public static readonly IReadOnlyList<string> All = new[]
        {
${contract.permissions.map((p) => `            ${toPascalCase(p.key)},`).join('\n')}
        };
    }
}
`;

const csOutputPath = path.join(rootDir, 'IELTSMaster.Shared', 'Security', 'GeneratedPermissionKey.g.cs');
fs.writeFileSync(csOutputPath, csCode, 'utf8');
console.log(`[CodeGen] Generated C# constants -> ${csOutputPath}`);

// 2. Generate TypeScript Code
const tsCode = `/**
 * <auto-generated>
 * This code was generated by scripts/generate-permissions.mjs
 * Source of Truth: IELTSMaster.Shared/Security/permissions-contract.json
 * Version: ${contract.version} | Last Updated: ${contract.lastUpdated}
 * </auto-generated>
 */

export const GeneratedPermissionKey = {
${contract.permissions
  .map(
    (p) => `  /** ${p.description} (${p.scope}) */
  ${toScreamingSnakeCase(p.key)}: '${p.key}',`
  )
  .join('\n')}
} as const;

export type GeneratedPermissionKey =
  (typeof GeneratedPermissionKey)[keyof typeof GeneratedPermissionKey];

export const ALL_PERMISSIONS: readonly GeneratedPermissionKey[] = [
${contract.permissions
  .map((p) => `  GeneratedPermissionKey.${toScreamingSnakeCase(p.key)},`)
  .join('\n')}
];
`;

const tsOutputPath = path.join(
  rootDir,
  'IELTSMaster.ELearning',
  'packages',
  'shared',
  'src',
  'roles.generated.ts'
);
fs.writeFileSync(tsOutputPath, tsCode, 'utf8');
console.log(`[CodeGen] Generated TypeScript constants -> ${tsOutputPath}`);

console.log('[CodeGen] Successfully synchronized contracts with C# and TypeScript codebases.');
